import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
const read = (file) => readFileSync(new URL(file,import.meta.url),'utf8')
const migration = read('../supabase/migrations/20261113110000_calendar_future_travel_override.sql')
const calendar = read('../src/pages/dashboard/Calendar.tsx')
const dialog = read('../src/components/game/CalendarTravelRescheduleDialog.tsx')
const css = read('../src/styles/calendar-player-activity.css')
const translated = read('../src/lib/calendarTravelRescheduleI18n.ts')
const schedule = read('../src/pages/dashboard/Schedule.tsx')

test('calendar shows options only on a future departure day, not for past journeys',()=>{
  assert.match(migration,/get_calendar_transfer_options_v1/)
  assert.match(migration,/l\.status='planned'/)
  assert.match(migration,/l\.departure_absolute_day>v_now/)
  assert.match(migration,/where row\.depart_day>v_now/)
  assert.match(calendar,/selectedDay>absoluteGameDay\(clock\.season,clock\.monthIndex,clock\.day\)/)
  assert.match(calendar,/option\.departure_absolute_day===selectedDay/)
  assert.match(calendar,/option\.has_planned_flight\?travelCopy\.changeFlight:travelCopy\.planTrip/)
})
test('calendar and preparation save to the SAME route preference',()=>{
  assert.match(dialog,/save_tournament_transfer_preference_v1/)
  assert.match(schedule,/save_tournament_transfer_preference_v1/)
  assert.match(dialog,/p_route_choice:choice/)
  assert.match(migration,/insert into public\.player_tournament_transfer_preferences/)
  assert.match(migration,/perform public\.get_tournament_transfer_preference_v1|public\.get_tournament_transfer_preference_v1\(p_player_id,p_competition_id\)/)
  assert.match(migration,/v_rebuild:=public\.rebuild_player_travel_plan_v1\(p_player_id\)/)
})
test('payment refund is exact, idempotent and only for untravelled planned flights',()=>{
  assert.match(migration,/t\.source_type='travel_leg'/)
  assert.match(migration,/t\.amount<0 and t\.category='travel'/)
  assert.match(migration,/l\.status='planned'/)
  assert.match(migration,/l\.departure_absolute_day>v_now/)
  assert.match(migration,/unused-travel-rebook-refund:/)
  assert.match(migration,/v_refund_total:=v_refund_total-r\.amount/)
  assert.match(migration,/if v_choice=p_route_choice then/)
  assert.doesNotMatch(migration,/refund_tournament_cancellation_costs_v1/)
  assert.doesNotMatch(migration,/delete from public\.career_finance_transactions/i)
})
test('preview shows flight, hotel, morale, fatigue, refund and private jet',()=>{
  assert.match(dialog,/quote_tournament_transfer_options_v1/)
  assert.match(dialog,/direct_flight_cost/)
  assert.match(dialog,/extra_hotel_nights/)
  assert.match(dialog,/arrival_fatigue/)
  assert.match(dialog,/direct_total_cost/)
  assert.match(dialog,/refundable_paid_cost/)
  assert.match(dialog,/words\.morale/)
  assert.match(dialog,/quote\.direct_flight_mode==='private_jet'/)
})
test('accessible compact control and modal have visible state and Save/Cancel buttons',()=>{
  assert.match(calendar,/className="tlg-calendar-change-flight"/)
  assert.match(dialog,/role="dialog" aria-modal="true"/)
  assert.match(dialog,/aria-pressed=\{choice==='direct'\}/)
  assert.match(dialog,/disabled=\{busy\|\|loading\|\|!quote\}/)
  assert.match(dialog,/onSaved\(choice,Number/)
  assert.match(css,/\.tlg-travel-reschedule-dialog/)
  assert.match(translated,/changeFlight:'Change flight'/)
  assert.match(translated,/changeFlight:'Flug ändern'/)
  assert.match(translated,/changeFlight:'Promeni let'/)
})
