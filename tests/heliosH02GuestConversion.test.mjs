import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
const read = p => readFileSync(new URL('../'+p,import.meta.url),'utf8')
const sql=read('supabase/migrations/20261120180500_helios_h02_guest_identity_conversion.sql')
const page=read('src/pages/auth/GuestRegistration.tsx')
const hook=read('src/hooks/useGuestTrialDisplay.ts')
const header=read('src/components/layout/GameHeader.tsx')
const sidebar=read('src/components/layout/GameSidebar.tsx')
const expiry=read('src/components/guest/GuestExpiryNotice.tsx')
const layout=read('src/components/layout/GameLayout.tsx')
const app=read('src/App.tsx')
const inventory=JSON.parse(read('docs/mobile-route-audit.json'))
const checklist=read('HELIOS_CHECKLIST.md')

test('H02: Supabase conversion retains original user identity and never copies progress',()=>{
  assert.match(page,/supabase\.auth\.updateUser\(/)
  assert.match(page,/\{ email: address \}/)
  assert.match(page,/\{ password \}/)
  assert.match(page,/supabase\.auth\.linkIdentity\(/)
  assert.match(page,/provider: 'google'/)
  assert.match(page,/!googleAvailable \|\| !status\?\.eligible/)
  assert.match(page,/get_my_tennis_guest_conversion_status_v1/)
  assert.doesNotMatch(page,/auth\.signUp|signInWithOAuth|\.from\('players'\)|owner_user_id/)
  assert.match(page,/cannot merge or overwrite two players automatically/i)
})

test('H02: only original user can query guest conversion state; timestamp recorded once',()=>{
  assert.match(sql,/AFTER UPDATE OF is_anonymous ON auth\.users/)
  assert.match(sql,/OLD\.is_anonymous IS TRUE AND NEW\.is_anonymous IS FALSE/)
  assert.match(sql,/NEW\.id = OLD\.id/)
  assert.match(sql,/converted_at = COALESCE\(converted_at, now\(\)\)/)
  assert.match(sql,/WHERE user_id = NEW\.id/)
  assert.match(sql,/v_id uuid := auth\.uid\(\)/)
  assert.match(sql,/WHERE user_id=v_id/)
  assert.match(sql,/REVOKE ALL ON FUNCTION public\.get_my_tennis_guest_conversion_status_v1\(\)/)
  assert.doesNotMatch(sql,/GRANT SELECT ON control_center_private\.tennis_guest_trials_v1 TO authenticated/)
  assert.doesNotMatch(sql,/UPDATE public\.tennis_premium_trials_v1|UPDATE public\.players|INSERT INTO auth\.users/)
})

test('H02: guests can register from header and mobile sidebar even when expired',()=>{
  assert.match(header,/user\?\.is_anonymous/)
  assert.match(header,/Register · Save Progress/)
  assert.match(header,/navigate\('\/guest\/register'\)/)
  assert.match(sidebar,/to="\/guest\/register"/)
  assert.match(sidebar,/onClick=\{onMobileClose\}/)
  assert.match(hook,/get_my_tennis_guest_trial_v1/)
  assert.match(hook,/60_000/)
  assert.match(hook,/visibilitychange/)
  assert.match(expiry,/state === 'expired'/)
  assert.match(expiry,/Register &amp; Continue/)
  assert.match(layout,/<GuestExpiryNotice \/>/)
  assert.match(app,/path="\/guest\/register"/)
  assert.ok(inventory.routes.some(x=>x.path==='/guest/register' && x.status==='blocked'))
  assert.match(checklist,/\*\*H02\*\*/)
  assert.match(checklist,/Guest Mode disabled/)
})
