-- Expand Private Life property destinations to 200 fixed cities and make apartment
-- availability category-specific. Each city offers between 1 and 7 of the 9
-- apartment categories. Dynamic player home towns remain separate and offer the
-- starter Compact City Flat using the generic Home Country image.

create table if not exists public.private_life_property_catalog_availability (
  location_code text not null references public.private_life_property_locations(code) on delete cascade,
  catalog_code text not null references public.private_life_asset_catalog(code) on delete cascade,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (location_code,catalog_code)
);

alter table public.private_life_property_catalog_availability enable row level security;

create index if not exists private_life_property_catalog_availability_catalog_idx
  on public.private_life_property_catalog_availability(catalog_code,active);

