import { useEffect, useState } from 'react'

import { supabase } from '../../lib/supabase'

interface MatchWeather {
  environment?: 'indoor' | 'outdoor'
  condition?: string
  temperature_c?: number
  wind_kmh?: number
  precipitation?: string
  affects_match?: boolean
  can_delay_match?: boolean
}

interface ReplaySummary {
  engine_version?: string | null
}

function formatTemperature(value?: number) {
  return typeof value === 'number' && Number.isFinite(value) ? `${Math.round(value)}°C` : '—'
}

function formatWind(value?: number) {
  return typeof value === 'number' && Number.isFinite(value) ? `${Math.round(value)} km/h wind` : 'Wind unavailable'
}

/**
 * Keeps the existing replay modal layout intact while replacing its legacy
 * Weather placeholder with the deterministic Match Engine v2 weather record.
 * Historical v1.1 matches explicitly remain marked as weather-unrecorded so
 * the UI never implies that weather affected a result generated by the old engine.
 */
export default function TournamentReplayWeatherEnhancement({ matchId }: { matchId: string }) {
  const [weather, setWeather] = useState<MatchWeather | null>(null)
  const [engineVersion, setEngineVersion] = useState<string | null>(null)
  const [loaded, setLoaded] = useState(false)

  useEffect(() => {
    let cancelled = false

    const load = async () => {
      const [weatherResult, replayResult] = await Promise.all([
        supabase.rpc('get_tournament_match_weather_v1', { p_match_id: matchId }),
        supabase.rpc('get_tournament_match_replay_v1', { p_match_id: matchId }),
      ])

      if (cancelled) return
      setWeather(weatherResult.error || !weatherResult.data ? null : weatherResult.data as MatchWeather)
      const replay = replayResult.error || !replayResult.data ? null : replayResult.data as ReplaySummary
      setEngineVersion(replay?.engine_version ?? null)
      setLoaded(true)
    }

    void load()
    return () => { cancelled = true }
  }, [matchId])

  useEffect(() => {
    let frame = 0
    let cancelled = false
    let strong: HTMLElement | null = null
    let small: HTMLElement | null = null

    const apply = () => {
      if (cancelled) return
      const card = document.querySelector<HTMLElement>('.tlg-replay-meta-item.weather-pending')
      strong = card?.querySelector<HTMLElement>('strong') ?? null
      small = card?.querySelector<HTMLElement>('small') ?? null

      if (!card || !strong || !small) {
        frame = window.requestAnimationFrame(apply)
        return
      }

      if (!loaded) {
        strong.textContent = 'Loading…'
        small.textContent = 'Reading official match conditions'
        return
      }

      if (engineVersion && engineVersion !== 'base-v2.0') {
        strong.textContent = 'Not recorded'
        small.textContent = 'Legacy match · weather did not affect this result'
        card.classList.remove('weather-pending')
        card.classList.add('weather-ready')
        return
      }

      if (!weather) {
        strong.textContent = 'Unavailable'
        small.textContent = 'Match weather could not be loaded'
        return
      }

      if (weather.environment === 'indoor') {
        strong.textContent = `Indoor · ${formatTemperature(weather.temperature_c)}`
        small.textContent = 'No weather effect · match stayed on schedule'
      } else {
        strong.textContent = `${weather.condition ?? 'Outdoor'} · ${formatTemperature(weather.temperature_c)}`
        small.textContent = `${formatWind(weather.wind_kmh)} · no delay or cancellation`
      }

      card.classList.remove('weather-pending')
      card.classList.add('weather-ready')
    }

    frame = window.requestAnimationFrame(apply)
    return () => {
      cancelled = true
      window.cancelAnimationFrame(frame)
    }
  }, [engineVersion, loaded, weather])

  return null
}
