'use strict';
const assert=require('node:assert/strict'),{choose,action,rollback}=require('./cutover-ownership.cjs');
const on={enabled:true,competitions:['canary']},off={...on,enabled:false};
const m={id:'m1',competition:'canary',status:'scheduled',legacySimulation:'none',owner:null,scope:'singles',eligible:true};
assert.equal(choose(m,off),'legacy');assert.equal(choose(m,on),'ace');
for(const legacySimulation of ['prepared','live','completed'])assert.equal(choose({...m,legacySimulation},on),'legacy');
for(const status of ['in_progress','completed','bye','walkover','cancelled'])assert.equal(choose({...m,status},on),'legacy');
assert.equal(choose({...m,started:true},on),'legacy');
assert.equal(choose({...m,scope:'doubles'},on),'legacy');
assert.equal(choose({...m,scope:'national_team'},on),'legacy');
assert.equal(choose({...m,competition:'ordinary'},on),'legacy');
assert.equal(choose({...m,eligible:false},on),'legacy');
assert.equal(choose({...m,owner:'ace'},off),'ace');
assert.equal(choose({...m,owner:'legacy'},on),'legacy');
assert.equal(action({...m,owner:'ace'},off,'legacy').status,'wrong_engine');
assert.equal(action({...m,owner:'ace'},off,'ace').status,'owner_allowed');
for(const actor of ['watchdog','guest_retirement','travel_no_show','health_surrender','admin_repair'])assert.equal(action({...m,owner:'ace'},off,actor).status,'owner_aware_handoff_required');
assert.deepEqual(rollback([{...m,owner:'ace'},{...m,id:'m2',owner:'ace',status:'completed'},{...m,id:'m3',owner:'legacy',status:'in_progress'}]),{newAdmissions:'legacy',drain:['m1'],retain:['m2'],canRemoveAce:false});
assert.equal(rollback([{...m,owner:'ace',status:'completed'}]).canRemoveAce,true);
assert.throws(()=>choose({...m,status:'unknown'},on),/Unknown match/);
console.log('PASS default legacy routing, existing simulation protection, opt-in singles canary, exclusive ownership, external mutation handoff and rollback drain');
