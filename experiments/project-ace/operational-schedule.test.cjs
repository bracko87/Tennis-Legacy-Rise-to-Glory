'use strict';
const assert=require('node:assert/strict'),{plan}=require('./schedule-gate.cjs'),{slot}=require('./world-clock.cjs');
const base=slot(1,1,1,0)/60;
const target={id:'b',status:'scheduled',feederReady:true,players:['p1','p2'],competition:'c',season:1,week:1,day:1,minute:600,firstWeek:1,lastWeek:1,courtCount:2,court:1};
const other={id:'a',status:'completed',players:['p1','p3'],competition:'c',court:2,startMinute:base+480,durationMinutes:60};
const run=(t,x,m=600,s=1)=>plan(t,x,(base+m)*60,s);
assert.equal(run(target,[other]).status,'ready');
assert.notEqual(run(target,[{...other,durationMinutes:61}]).status,'ready');
const court={...other,players:['p3','p4'],court:1,startMinute:base+525};
assert.equal(run(target,[court]).status,'ready');
assert.notEqual(run(target,[{...court,durationMinutes:61}]).status,'ready');
assert.equal(run(target,[{...other,status:'live'}],1000).status,'waiting_live_conflict');
assert.equal(run(target,[],600,0).status,'paused');
assert.equal(run({...target,feederReady:false},[]).status,'not_eligible');
assert.equal(run(target,[],599).status,'not_due');
const cross=run(target,[{...other,competition:'different'}]);assert.equal(cross.status,'rescheduled');assert.equal(cross.day,2);
const moved=run(target,[{...court,durationMinutes:200}]);assert.equal(moved.status,'rescheduled');assert.equal(moved.court,2);
assert.equal(run({...target,day:7},[],6*1440+1291).status,'blocked');
assert.equal(run({...target,minute:607},[],607).gameMinute,base+607);
assert.equal(run(target,[],615).gameMinute,base+615);
assert.notEqual(run(target,[{...other,completedGameMinute:base+550}]).status,'ready');
console.log('PASS 14 operational scheduling assertions: player/court boundaries, live hold, pause, feeders, due time, cross-competition, alternate court, phase exhaustion, off-grid and actual completion');
