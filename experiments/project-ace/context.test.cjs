'use strict';
const assert=require('node:assert/strict');
const e=require('./engine.cjs'),{fixtureProfiles}=require('./profiles.cjs'),c=require('./match-context.cjs'),{contextualAdvice}=require('./analysis.cjs'),a=require('./match-service.cjs');
const make=(w='normal',settings={},surface='hard')=>e.createMatch({players:fixtureProfiles('balanced','balanced',surface,false,settings),surface,weather:c.environment(w),version:'ace-context-0.5',seed:6});
const base=make(),left=make('normal',{hands:['left','right']});
assert.deepEqual(e.probabilities(base,0,true),e.probabilities(left,0,true));
base.tactics[0].target='Backhand';left.tactics[0].target='Backhand';
assert.ok(e.probabilities(left,0,true).serverWin>e.probabilities(base,0,true).serverWin);
const windy=make('windy');assert.ok(e.probabilities(windy,0,true).firstIn<e.probabilities(make(),0,true).firstIn);
const missing=make('normal',{equipment:['missing-racket','standard']});
assert.ok(e.probabilities(missing,0,true).serverWin<e.probabilities(make(),0,true).serverWin);
assert.throws(()=>c.environment('bad'));assert.throws(()=>c.metadata({hand:'bad'}));
assert.throws(()=>c.validateWeather({...c.environment('indoor'),windKmh:20}));
const hot=make('hot'),normal=make();assert.ok(c.exertion(hot.players[0],hot.weather)>c.exertion(normal.players[0],normal.weather));
assert.deepEqual(e.stepGame(hot),e.stepGame(JSON.parse(JSON.stringify(hot))));
const p=e.observable(make()).players,stats=[{servicePoints:0,firstIn:0,doubleFaults:0,unforcedErrors:0},{servicePoints:0,firstIn:0,doubleFaults:0,unforcedErrors:0}];
assert.ok(contextualAdvice(p,stats,0,0,[],'hard',c.environment()).some(x=>x.patch.approach==='Aggressive'));
const admin={id:'a',verified:true,isAdmin:true},policy={enabled:true,adminId:'a'};
const r=a.createFixture({id:'context',players:make().players,seed:6,startAt:1000,weather:c.environment('hot')},admin,policy,0);
const v=a.view(r,admin,policy,1000);assert.equal(v.engineVersion,'ace-context-0.5');assert.equal(v.weather.temperatureC,34);
assert.equal('equipment' in v.players[0],false);
assert.equal(fixtureProfiles('aggressive','balanced','hard',false,{})[0].style,'Aggressive Baseliner');
const automatic=a.advance(r,1000);
assert.ok(automatic.applied[1]);
assert.equal(automatic.applied[1].game,1);
console.log('PASS context validation, weather, equipment, handedness without baseline bonus, restart, visible advice and default engine');
