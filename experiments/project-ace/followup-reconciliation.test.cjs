'use strict';
const assert=require('node:assert/strict'),{candidates,enqueue,record}=require('./followup-reconciliation.cjs'),{slot}=require('./world-clock.cjs');
const played={id:'played',status:'completed',players:['a','b'],season:1,week:1,day:1,minute:600,actualDuration:180,estimatedDuration:150};
const match=(id,minute,extra={})=>({id,status:'scheduled',players:['a','c'],season:1,week:1,day:1,minute,...extra});
const matches=[match('z',840),match('b',700),match('a',700),match('outside',841),match('before',599),match('unrelated',700,{players:['x','y']}),match('live',700,{status:'live'}),match('missing',700,{players:['a',null]}),match('cross',720,{competition:'other'})];
assert.deepEqual(candidates(played,matches),['a','b','cross','z']);
assert.deepEqual(candidates({...played,actualDuration:150},matches),[]);
assert.deepEqual(candidates({...played,status:'live'},matches),[]);
assert.deepEqual(candidates({...played,actualDuration:null},matches),[]);
assert.deepEqual(candidates({...played,completedGameMinute:slot(1,1,1,800)/60},matches),['a','b','cross','z','outside']);
assert.throws(()=>candidates(played,[matches[0],matches[0]]),/Duplicate/);
const q=enqueue([],played,matches),frozen=JSON.stringify(q);
assert.equal(enqueue(q,played,[]),q);
assert.throws(()=>enqueue(q,{...played,actualDuration:181},matches),/Conflicting/);
const failed=record(q,'played','a','error');
assert.equal(failed[0].items[0].status,'pending');
assert.equal(failed[0].items[0].attempts,1);
const blocked=record(failed,'played','a','blocked');
assert.equal(blocked[0].items[0].status,'pending');
const done=record(blocked,'played','a','rescheduled');
assert.equal(done[0].items[0].status,'done');
assert.equal(done[0].items[0].attempts,3);
assert.equal(record(done,'played','a','rescheduled'),done);
assert.equal(JSON.stringify(q),frozen);
assert.equal(done[0].items[1].attempts,0);
assert.throws(()=>record(done,'played','unknown','ready'),/Unknown/);
assert.throws(()=>record(done,'played','b','paid'),/Invalid/);
assert.deepEqual(JSON.parse(JSON.stringify(done)),done);
console.log('PASS follow-up selection, overrun boundaries, late actual completion, immutable evidence, retry and duplicate receipt protection');
